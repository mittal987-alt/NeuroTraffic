// Initializes Firebase before the app starts, sets up FCM (Firebase
// Cloud Messaging) so the device can receive pushes, and checks for
// an existing login session to decide whether to show the Dashboard
// or the Login screen on launch.

import 'package:flutter/material.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:firebase_messaging/firebase_messaging.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'screens/login_screen.dart';
import 'screens/dashboard_screen.dart';
import 'services/auth_service.dart';

// Must be a top-level function (not inside a class) -- this handles
// notifications that arrive while the app is fully closed/backgrounded.
@pragma('vm:entry-point')
Future<void> _firebaseBackgroundHandler(RemoteMessage message) async {
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  print('Background message received: ${message.notification?.title}');
}

void main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  // Register the background handler
  FirebaseMessaging.onBackgroundMessage(_firebaseBackgroundHandler);

  runApp(const TrafficVisionApp());
}

class TrafficVisionApp extends StatefulWidget {
  const TrafficVisionApp({super.key});

  @override
  State<TrafficVisionApp> createState() => _TrafficVisionAppState();
}

class _TrafficVisionAppState extends State<TrafficVisionApp> {
  @override
  void initState() {
    super.initState();
    _setupNotifications();
  }

  Future<void> _setupNotifications() async {
    final messaging = FirebaseMessaging.instance;

    // Ask the user for notification permission (required on iOS,
    // and on Android 13+).
    await messaging.requestPermission(alert: true, badge: true, sound: true);

    // Get this device's unique FCM token. In a real app you'd send
    // this to your backend and store it (so the backend knows WHERE
    // to send pushes). We print it for now so you can copy it for
    // manual testing.
    final token = await messaging.getToken();
    print('FCM TOKEN (copy this for testing): $token');

    // Handle notifications that arrive while the app is OPEN and in
    // the foreground -- these don't show automatically like background
    // ones do, so we show our own dialog/snackbar.
    FirebaseMessaging.onMessage.listen((RemoteMessage message) {
      print('Foreground message: ${message.notification?.title} - ${message.notification?.body}');
      // TODO: show a SnackBar or in-app banner here later.
    });
  }

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'TrafficVision AI',
      theme: ThemeData(primarySwatch: Colors.blue, useMaterial3: true),
      home: const _AuthGate(),
      debugShowCheckedModeBanner: false,
    );
  }
}

/// Checks whether a valid login session already exists (a saved token
/// that still verifies against the backend) and routes straight to
/// the Dashboard if so -- otherwise shows the Login screen.
class _AuthGate extends StatelessWidget {
  const _AuthGate();

  @override
  Widget build(BuildContext context) {
    return FutureBuilder<bool>(
      future: AuthService().isLoggedIn(),
      builder: (context, snapshot) {
        if (snapshot.connectionState != ConnectionState.done) {
          return const Scaffold(body: Center(child: CircularProgressIndicator()));
        }
        return snapshot.data == true
            ? const DashboardScreen()
            : LoginScreen();
        },
    );
  }
}